/** 帮助视图：使用说明、算法说明、故障排查。 */

import { h } from './dom.ts';

export function renderHelp(root: HTMLElement): void {
  const sec = (title: string, ...body: Array<Node | string>) =>
    h('div', { class: 'card help' }, h('h3', {}, title), ...body);

  root.appendChild(
    h(
      'div',
      { class: 'card help' },
      h('h2', {}, '快速上手'),
      h(
        'ol',
        {},
        h('li', {}, '插上你的 USB HID 直键练习器（它会被系统当成一个鼠标）。'),
        h('li', {}, '到「课程」选一课，比如「第 1 课 点与划的节奏」。'),
        h('li', {}, '回到「练习」，把鼠标移到键盘区，点「武装手键」，按 Esc 可以随时解除。'),
        h('li', {}, '像拍真直键一样点击：短按 = 点（dit），长按 = 划（dah）。'),
        h('li', {}, '每个字的上方显示它的摩尔斯码；发对了变绿，发错了变红并告诉你发成了什么。'),
        h('li', {}, '发完一条点「结算」，会给你准确率、逐字差异、节奏评分，并把整段重新复核一遍。'),
      ),
      h(
        'p',
        { class: 'dim' },
        '没有硬件也能练：鼠标左键、右键，或键盘的空格 / J / K / 回车都可以当直键。',
      ),
    ),
  );

  root.appendChild(
    sec(
      '它是怎么"听懂"你的手键的',
      h(
        'p',
        {},
        '核心是三个想法：不写死阈值、允许回改、用整段报文来纠错。',
      ),
      h(
        'table',
        { class: 'grid' },
        h(
          'tbody',
          {},
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '自适应点长')),
            h(
              'td',
              {},
              '程序在线估计你的"点"有多长（默认从 12 WPM 起，即约 100ms）。每一批按键都会重新做一次两簇聚类',
              '（2-means），同时估出"点长、划长、以及你手抖的相对幅度"。所以它不怕你的点和划时长跟标准不一样，',
              '也不怕你越拍越快；分类时比较的是对数似然，而不是"小于 80ms 算点"这种死阈值。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '全局最优分割')),
            h(
              'td',
              {},
              '每按一下，程序都会把「到目前为止的全部按键」重新解一遍：枚举"哪些连续按键属于同一个字符"的所有切分方式，',
              '每个字符内部走摩尔斯前缀树，字与字之间按真实间隔算代价，取整段代价最小的路径（动态规划 / Viterbi）。',
              '线上判断和结束时的复核用的是同一套逻辑，所以不会出现两套答案。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '可回改')),
            h(
              'td',
              {},
              '只有"最近几轮重算都一致"的前缀才会落账成实心字；尾部随时可能被后面的按键改写。',
              '典型例子：连发四个划，中间会先猜成 "ETT"，等第四个划落下时整段变成 "5" —— 这时屏幕上会提示',
              '"已回改前面第 N 个字符：T → 5"。抄收区里的斜体字就是"还没落定、可能会变"的部分。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '停顿 = 字间 / 词间')),
            h(
              'td',
              {},
              '两次点击之间超过约 3 个单位时间（可在设置里改）就认为一个字符结束了；',
              '更长的停顿（约 7 个单位）则被当成"词间隔"，等价于一个空格。',
              '所以你不需要真的发空格，长报文也可以中途停下来喘气。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '全局复核')),
            h(
              'td',
              {},
              '结算时会对整段按键再做一次全局最优解释，把在线过程中因为信息不足而判错的字修回来，',
              '并给出整段的置信度与你的节奏评分。',
            ),
          ),
        ),
      ),
    ),
  );

  root.appendChild(
    sec(
      '关于硬件与精度（重要）',
      h(
        'ul',
        {},
        h(
          'li',
          {},
          'USB 鼠标类 HID 设备最快 8ms（USB 全速）或 1ms（高速）上报一次，',
          '再经过操作系统与浏览器的处理，一次按键的时长误差大约 ±8~16ms。',
        ),
        h(
          'li',
          {},
          '在 12 WPM（点长 100ms）下这点误差完全够用；到了 25 WPM 以上（点长 48ms）就开始变粗糙，',
          '因为量化的台阶相对于点长变大了。真要在高速下高精度识别，需要用能上报真实时间戳的串口 / 键盘设备。',
        ),
        h(
          'li',
          {},
          '如果你的设备是"键盘模式"（HID keyboard），那它在浏览器里就是按键事件，',
          '默认空格 / J / K / 回车已经映射好了；如果是别的键，可以在设置里换（后续可加自定义键位）。',
        ),
        h(
          'li',
          {},
          '双击检测不会干扰这里：程序监听的是 mousedown / mouseup，不是 click。',
        ),
      ),
    ),
  );

  root.appendChild(
    sec(
      '如果识别不准，按这个顺序排查',
      h(
        'ol',
        {},
        h('li', {}, '打开「设置」拉到最下面的校准台，连拍 30 下，看点长 / 划长是不是稳定收敛，误判概率是否很低。'),
        h('li', {}, '如果你习惯"点比标准更短、划比标准更长"，没问题，模型会自适应；但如果点和划的时长分布重叠，就要先放慢速度练节奏。'),
        h('li', {}, '重点练「第 1 课」的 E / T，把"1 单位 vs 3 单位"的手感做出来。'),
        h('li', {}, '别追求快：先把点划比例做稳，速度自然会上去。节奏分（0-100）比速度更能说明问题。'),
        h('li', {}, '诊断面板会列出每一次按键的毫秒数、判成点还是划、间隔多少个单位。看那里的数字最直观。'),
      ),
    ),
  );

  root.appendChild(
    sec(
      '课程内容说明',
      h(
        'p',
        {},
        '所有练习都是有意义的报文：从 E/T、A/N 这种最小节奏对比，到 K、R、DE、TU、FB 这些通联缩略语，',
        '再到 RST 599、CQ CQ DE <你的呼号> K，最后是完整的 QSO 对话。每条都给出中文含义，目标是从一开始就',
        '把码型和"意思"绑在一起，而不是听一串声音再逐字翻译。',
      ),
      h(
        'p',
        {},
        '第 8 课里的过程信号（prosign）用键盘符号代替，因为 QWERTY 上没有对应的键：',
        h('code', {}, '+'), ' = AR（报文结束）、', h('code', {}, '='), ' = BT（分段）、',
        h('code', {}, '!'), ' = SK（结束联络）、', h('code', {}, '('), ' = KN（只请指定台回答）。',
        '它们本身要连拍，不要按键盘上那个符号的摩尔斯码去发。',
      ),
    ),
  );

  root.appendChild(
    sec(
      '键盘快捷键',
      h(
        'table',
        { class: 'grid' },
        h('tbody', {}, ...keyRows()),
      ),
    ),
  );
}

function keyRows(): HTMLElement[] {
  const rows: Array<[string, string]> = [
    ['Esc', '武装 / 解除手键'],
    ['R', '听当前这条的参考发送（标准节奏）'],
    ['N', '下一条'],
  ];
  return rows.map(([k, v]) => h('tr', {}, h('td', {}, h('code', {}, k)), h('td', {}, v)));
}
