/**
 * 帮助页：使用方法、识别原理、排查顺序。
 *
 * 文字风格约定（全站一致）：短句陈述，不用语气词，不用感叹号，
 * 不解释显而易见的事，不替用户做决定。
 */

import { h } from './dom.ts';

export function renderHelp(root: HTMLElement): void {
  const sec = (title: string, ...body: Array<Node | string>) =>
    h('div', { class: 'card help' }, h('h3', {}, title), ...body);
  const key = (k: string) => h('code', {}, k);

  root.appendChild(
    h(
      'div',
      { class: 'card help' },
      h('h2', {}, '使用方法'),
      h(
        'ol',
        {},
        h('li', {}, '把直键练习器接到电脑上。系统会把它识别为鼠标，这是正常的。'),
        h('li', {}, '在「课程」里选一课。'),
        h('li', {}, '回到「练习」，鼠标停在按键区域内，按空格键或点「开始」。'),
        h('li', {}, '短按是点，长按是划。'),
        h('li', {}, '每个字下面写着它该怎么发。发对显示绿色，发错显示红色，并标出实际发出的字符。'),
        h('li', {}, '发完点「成绩」，查看逐字对照、点划时长和节奏评分。'),
      ),
      h(
        'p',
        {},
        '没有练习器时，鼠标左键、右键，以及键盘的 ',
        key('空格'),
        '、',
        key('J'),
        '、',
        key('K'),
        '、',
        key('回车'),
        ' 都可以当直键。按 ',
        key('Esc'),
        ' 开始或停止。',
      ),
    ),
  );

  root.appendChild(
    sec(
      '识别原理',
      h('p', {}, '程序不预设“多少毫秒算点”。点划时长和判据都从你的实际拍发中估计。'),
      h(
        'table',
        { class: 'grid' },
        h(
          'tbody',
          {},
          h(
            'tr',
            {},
            h('td', {}, '点划时长'),
            h(
              'td',
              {},
              '每收到一批按键，就按当前模型把它们重新分成“点”“划”两堆，据此更新点长、划长和两者的离散程度。',
              '手快或手慢都不需要设置；点划比偏离标准的 1:3 也会照样跟随。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, '整段重解'),
            h(
              'td',
              {},
              '每按一下，程序把此前所有按键整体重新解码一次：枚举所有可能的分字方式，取整体代价最小的一种。',
              '判据是全部证据，而不是单次按键的即时猜测。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, '待定与修正'),
            h(
              'td',
              {},
              '只有连续几轮解码结果一致的字才判定为已确定，显示为实心字；其余显示为斜体“待定”。',
              '新按键改变结论时，先前判定的字会被改写，并显示“已修正：T → 5”。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, '静音分字'),
            h(
              'td',
              {},
              '两次按键之间的静音达到约 3 个单位时间（可在设置中调整），判定为一个字结束；',
              '达到约 7 个单位则判定为词间隔，等同空格。因此不需要真的发空格，句子中间也可以随时停顿。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, '成绩复核'),
            h(
              'td',
              {},
              '点「成绩」时会对整段再解码一次，修正过程中因信息不足而产生的误判，并给出整段把握度。',
            ),
          ),
        ),
      ),
    ),
  );

  root.appendChild(
    sec(
      '设备与计时精度',
      h(
        'ul',
        {},
        h(
          'li',
          {},
          '鼠标类 USB 设备每 8ms（全速）或 1ms（高速）上报一次，再经系统和浏览器处理，',
          '单次按键时长的误差约为 ±8~16ms。',
        ),
        h(
          'li',
          {},
          '12 WPM（点长约 100ms）时该误差可以忽略；25 WPM 以上（点长约 48ms）开始明显，',
          '因为量化台阶相对于点长变大了。更高速度下若要求精确，需要能提供真实时间戳的设备。',
        ),
        h(
          'li',
          {},
          '若设备被系统识别为键盘，在浏览器中就是按键事件。默认支持空格、J、K、回车，暂不支持自定义键位。',
        ),
        h('li', {}, '程序取按下与抬起两个时刻，不使用系统的单击事件，因此双击检测不影响计时。'),
      ),
    ),
  );

  root.appendChild(
    sec(
      '识别不准时的排查顺序',
      h(
        'ol',
        {},
        h('li', {}, '在「设置」底部的校准台连拍几十下，看点长、划长是否收敛，“可能误判比例”是否偏低。'),
        h('li', {}, '点划时长与标准不同没有关系，程序会跟随；两者分布重叠时需要先放慢速度，把长短拉开。'),
        h('li', {}, '重点练第 1 课的 E / T，先建立“点是一、划是三”的手感。'),
        h('li', {}, '节奏分比速度更能说明问题。'),
        h('li', {}, '「按键记录」列出每一下的时长、判定和间隔，数字异常时从那里核对最直接。'),
      ),
      h('p', {}, '被忽略的按键会在记录里以 × 开头并注明原因，正常拍发不应出现这种行。'),
    ),
  );

  root.appendChild(
    sec(
      '课程内容',
      h(
        'p',
        {},
        '没有随机字母。内容从 E/T、A/N 这类最小对比开始，到常用简语、信号报告、呼叫格式，最后是完整通联。',
        '每条都注明中文含义，便于把声音和意思一起记住。',
      ),
      h(
        'p',
        {},
        '第 8 课的过程信号（prosign）要连着一口气发完，中间不留空。普通键盘上没有对应按键，本站约定用四个符号代替：',
        key('+'),
        ' 是 AR（一段发送完毕），',
        key('='),
        ' 是 BT（分段），',
        key('!'),
        ' 是 SK（结束联络），',
        key('('),
        ' 是 KN（只请指定电台回答）。',
      ),
    ),
  );

  root.appendChild(
    sec(
      '快捷键',
      h(
        'table',
        { class: 'grid' },
        h(
          'tbody',
          {},
          h('tr', {}, h('td', {}, key('Esc')), h('td', {}, '开始或停止')),
          h('tr', {}, h('td', {}, key('R')), h('td', {}, '试听本条的标准发送')),
          h('tr', {}, h('td', {}, key('N')), h('td', {}, '下一条')),
        ),
      ),
    ),
  );
}
