/** 帮助页：怎么用、程序是怎么认你的码的、发不准怎么办。 */

import { h } from './dom.ts';

export function renderHelp(root: HTMLElement): void {
  const 段 = (title: string, ...body: Array<Node | string>) =>
    h('div', { class: 'card help' }, h('h3', {}, title), ...body);

  root.appendChild(
    h(
      'div',
      { class: 'card help' },
      h('h2', {}, '怎么开始'),
      h(
        'ol',
        {},
        h('li', {}, '把你的 USB 直键练习器插上（电脑会把它当成一个鼠标，这是正常的）。'),
        h('li', {}, '到「课程」挑一课。第一次练就从第 1 课开始，先把“点”和“划”的手感分开。'),
        h('li', {}, '回到「练习」，把鼠标移到那块区域，点「开始拍发」。'),
        h('li', {}, '然后就按你的手键：短按是“点”，长按是“划”。'),
        h('li', {}, '屏幕上每个字下面都写着它该怎么发。发对了变绿，发错了变红，还会告诉你你实际发成了什么。'),
        h('li', {}, '发完一条点「看看成绩」，能看到哪几个字发错了、节奏稳不稳。'),
      ),
      h(
        'p',
        { class: 'dim' },
        '手上暂时没有练习器也没关系：鼠标左键、右键，或者键盘上的空格 / J / K / 回车，都能当手键用。',
      ),
      h('p', { class: 'dim' }, '想停下来，按 Esc，或者再点一次那个按钮。'),
    ),
  );

  root.appendChild(
    段(
      '它是怎么听懂你的手键的',
      h('p', {}, '一句话：它不认识“多少毫秒算点”，而是边听边摸你的习惯。三件事最关键。'),
      h(
        'table',
        { class: 'grid' },
        h(
          'tbody',
          {},
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '先摸清你的点有多长')),
            h(
              'td',
              {},
              '程序不知道你手快手慢，所以每来一批按键，它都会把这些按键的时长重新分成两堆',
              '（一堆积是点、一堆是划），顺便算出你手有多抖。所以你的点比别人长、比别人短都没关系，',
              '它跟着你走；你越拍越快，它也跟得上。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '每按一下，整句话重解一遍')),
            h(
              'td',
              {},
              '每按一下之后，程序会把“到目前为止按过的所有键”整体重新解一次：',
              '把这一串按键切成一个个字，切法有很多种，它挑最合理的那一种。',
              '这样做的好处是——判断用的是全部证据，而不是“就这几十毫秒，我猜是点吧”。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '拿不准就先不写死')),
            h(
              'td',
              {},
              '只有最近几轮重解结果都一样的字，才会当成“已经定了”写成实心字；',
              '后面那几个还没定的，会画成斜体。等你多发几下、证据足了，它会把前面认错的字改过来 ——',
              '你在屏幕上会看到类似“前面那个字本来认成 T，现在改成 5”的提示。',
              '这是故意的：手键本来就有模糊地带，早下结论反而更容易错。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '停下来就算一个字发完了')),
            h(
              'td',
              {},
              '两次按键之间静了大约 3 个单位的时间（可在设置里改），就认为上一个字发完了；',
              '静得更久（约 7 个单位）则当成词与词之间的空档，等于一个空格。',
              '所以发长句子的时候你可以随时停下来喘口气，不用真的去发空格。',
            ),
          ),
          h(
            'tr',
            {},
            h('td', {}, h('code', {}, '看成绩时会再解一遍')),
            h(
              'td',
              {},
              '点「看看成绩」的时候，程序会把整段从头到尾最优地再解一次，',
              '把过程中因为信息不够而认错的字纠正过来，并给出整段的把握程度。',
            ),
          ),
        ),
      ),
    ),
  );

  root.appendChild(
    段(
      '关于你的设备和精度（值得看一眼）',
      h(
        'ul',
        {},
        h(
          'li',
          {},
          '鼠标类的 USB 设备最快 8ms（USB 全速）或 1ms（高速）往上报一次，再经过系统和浏览器，',
          '所以你按下的时长会有大约 ±8~16ms 的误差。',
        ),
        h(
          'li',
          {},
          '12 WPM（点长约 100ms）时这点误差完全没关系；到 25 WPM 以上（点长 48ms）就开始显出来了，',
          '因为误差台阶相对于点长变大了。真要在高速下也认得准，得用能报真实时间戳的设备。',
        ),
        h(
          'li',
          {},
          '如果你的设备是键盘型的（电脑把它当键盘），那它在浏览器里就是按键事件。',
          '默认空格 / J / K / 回车都能用；想用别的键，目前的版本还没做自定义键位。',
        ),
        h('li', {}, '程序看的是“按下”和“抬起”两个时刻，不是系统的“单击”，所以双击检测不会干扰计时。'),
      ),
    ),
  );

  root.appendChild(
    段(
      '发得不准？照这个顺序查',
      h(
        'ol',
        {},
        h('li', {}, '先去「设置」最下面的校准台，连拍几十下，看点长、划长是不是稳定下来，“可能听错的比例”是不是很低。'),
        h('li', {}, '如果你习惯把点发得更短、划发得更长，没问题，程序会跟着你；但如果点划的时长开始互相重叠，就得先放慢速度把节奏做稳。'),
        h('li', {}, '重点练第 1 课的 E / T：一个点、一个划，把“1 比 3”的手感做出来。这一步做扎实，后面都会顺。'),
        h('li', {}, '别急着快。节奏分（满分 100）比速度更能说明问题。'),
        h('li', {}, '「按键记录」里写着每一下按了多久、被当成点还是划、离上一下隔了多久。数字对不上时，看那里最直观。'),
      ),
      h(
        'p',
        { class: 'dim' },
        '如果某一下明显被漏掉了，那一行会以 × 开头，并写明为什么没算它 —— 正常拍发不该出现这种行。',
      ),
    ),
  );

  root.appendChild(
    段(
      '练的都是什么内容',
      h(
        'p',
        {},
        '没有随机字母。所有内容都是有意义的：从 E/T、A/N 这种最小对比，到 K、R、DE、TU、FB 这些通联常用的简语，',
        '再到 RST 599、CQ CQ DE <你的呼号> K，最后是完整的通联过程。每条都配了中文意思，',
        '目的是让你一开始就把“声音”和“意思”绑在一起，而不是听一串滴答再去逐字翻译。',
      ),
      h(
        'p',
        {},
        '第 8 课里的几个过程信号（prosign）用键盘符号顶替，因为普通键盘上没有对应的键：',
        h('code', {}, '+'),
        ' 是 AR（一段发完），',
        h('code', {}, '='),
        ' 是 BT（分段），',
        h('code', {}, '!'),
        ' 是 SK（结束联络），',
        h('code', {}, '('),
        ' 是 KN（只请对方回答）。它们本身要连着一气发完，别按那个符号的摩尔斯码去发。',
      ),
    ),
  );

  root.appendChild(
    段(
      '键盘快捷键',
      h(
        'table',
        { class: 'grid' },
        h(
          'tbody',
          {},
          h('tr', {}, h('td', {}, h('code', {}, 'Esc')), h('td', {}, '开始 / 停止拍发')),
          h('tr', {}, h('td', {}, h('code', {}, 'R')), h('td', {}, '听一遍这一条的标准示范（还没开始拍发时）')),
          h('tr', {}, h('td', {}, h('code', {}, 'N')), h('td', {}, '换下一条')),
        ),
      ),
    ),
  );
}
